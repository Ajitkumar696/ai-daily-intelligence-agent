"""Final audio mix: normalised voice + optional ducked background music (FFmpeg).

Music is either generated by FFmpeg itself (a soft synthesised pad - no files,
so nothing copyrighted is bundled) or a file the user supplies and has the
rights to use. ``VIDEO_MUSIC=off`` disables it.
"""
import subprocess
from pathlib import Path
from typing import List, Optional, Tuple

from .config import VideoConfig

# A-minor pad: root, fifth, octave and ninth with slow swells and a gentle pulse.
_PAD = (
    "0.22*sin(2*PI*110*t)"
    "+0.15*sin(2*PI*164.81*t)*(0.7+0.3*sin(2*PI*0.11*t))"
    "+0.13*sin(2*PI*220*t)*(0.6+0.4*sin(2*PI*0.07*t))"
    "+0.08*sin(2*PI*261.63*t)*(0.5+0.5*sin(2*PI*0.05*t))"
)
_PULSE = "(0.88+0.12*sin(2*PI*1.6*t))"


class MixError(RuntimeError):
    pass


def resolve_music(config: VideoConfig, seconds: float) -> Tuple[Optional[List[str]], str, List[str]]:
    """Returns (ffmpeg input args or None, description, warnings)."""
    warnings: List[str] = []
    mode = config.music_mode
    if mode == "off":
        return None, "off", warnings
    if mode == "file":
        path = Path(config.music_file) if config.music_file else None
        if path and path.is_file() and path.stat().st_size > 0:
            return (["-stream_loop", "-1", "-i", str(path)], f"file: {path.name}", warnings)
        warnings.append("Background music file not found or unset; using the generated "
                        "music pad instead (set VIDEO_MUSIC=off to disable music).")
    expr = f"{_PAD}*{_PULSE}"
    src = f"aevalsrc={expr}|{expr}:s=48000:d={seconds:.3f}"
    return (["-f", "lavfi", "-i", src], "generated pad", warnings)


def build_mix_command(ffmpeg: str, voice_wav: Path, out_wav: Path, seconds: float,
                      music_args: Optional[List[str]], music_volume: float = 0.16) -> List[str]:
    """FFmpeg command: loudness-normalised voice, music ducked under it, limited, 48 kHz stereo."""
    fmt = "aformat=sample_rates=48000:channel_layouts=stereo"
    voice = f"[0:a]highpass=f=70,loudnorm=I=-16:TP=-1.5:LRA=11,{fmt}"
    cmd = [ffmpeg, "-y", "-hide_banner", "-loglevel", "error", "-i", str(voice_wav)]
    if music_args:
        fade_out_at = max(seconds - 2.5, 0.0)
        graph = (
            f"{voice},asplit=2[vo][key];"
            f"[1:a]{fmt},lowpass=f=1400,volume={music_volume:.3f},"
            f"afade=t=in:st=0:d=1.5,afade=t=out:st={fade_out_at:.3f}:d=2.5[mu];"
            "[mu][key]sidechaincompress=threshold=0.02:ratio=9:attack=15:release=450[duck];"
            "[vo][duck]amix=inputs=2:duration=first:normalize=0,alimiter=limit=0.89[aout]"
        )
        cmd += music_args
    else:
        graph = f"{voice},alimiter=limit=0.89[aout]"
    cmd += ["-filter_complex", graph, "-map", "[aout]", "-t", f"{seconds:.3f}",
            "-ar", "48000", "-ac", "2", "-c:a", "pcm_s16le", str(out_wav)]
    return cmd


def mix_audio(ffmpeg: str, voice_wav: Path, out_wav: Path, seconds: float,
              config: VideoConfig) -> Tuple[str, List[str]]:
    """Run the mix. A broken optional music source falls back to voice-only; voice errors raise."""
    music_args, description, warnings = resolve_music(config, seconds)
    attempts = [(music_args, description)]
    if music_args:
        attempts.append((None, "off (music failed)"))
    last = ""
    for args, desc in attempts:
        cmd = build_mix_command(ffmpeg, voice_wav, out_wav, seconds, args, config.music_volume)
        try:
            res = subprocess.run(cmd, capture_output=True, text=True, timeout=300)
        except (OSError, subprocess.SubprocessError) as exc:
            raise MixError(f"Could not run FFmpeg for the audio mix: {exc}") from exc
        if res.returncode == 0 and out_wav.exists() and out_wav.stat().st_size > 0:
            if args is None and music_args:
                warnings.append("Background music failed and was skipped: " + last)
            return desc, warnings
        last = res.stderr.strip()[-300:]
    raise MixError(f"Audio mix failed: {last}")